const MESSAGES: Record<Locale, Record<TranslationKey, string>> = {
  "en-US": enUS,
  "es-ES": esES,
  "pt-BR": ptBR,
};

type I18nContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey, params?: InterpolationParams) => string;
};

const I18nContext = React.createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = React.useState(readStoredLocale);

  React.useEffect(() => {
    document.documentElement.lang = locale;
    localStorage.setItem(LOCALE_STORAGE_KEY, locale);
  }, [locale]);

  const setLocale = React.useCallback((next: Locale) => {
    setLocaleState(next);
  }, []);

  const t = React.useCallback(
    (key: TranslationKey, params?: InterpolationParams) => translate(locale, key, params),
    [locale],
  );

  const value = React.useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function formatStatus(status: string, t: I18nContextValue["t"]): string {
  const key = `status.${status}` as TranslationKey;
  return hasTranslation(key) ? t(key) : status;
}

export function hasTranslation(key: string): key is TranslationKey {
  return Object.prototype.hasOwnProperty.call(ptBR, key);
}

export function normalizeLocale(value: string | null | undefined): Locale {
  const normalized = value?.replace("_", "-").toLowerCase();
  if (normalized === "en" || normalized === "en-us") return "en-US";
  if (normalized === "es" || normalized === "es-es") return "es-ES";
  if (normalized === "pt" || normalized === "pt-br") return "pt-BR";
  return DEFAULT_LOCALE;
}

export function translate(locale: Locale, key: TranslationKey, params: InterpolationParams = {}): string {
  const template = MESSAGES[locale][key] ?? ptBR[key];
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? ""));
}

export function useI18n() {
  const context = React.useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used within <I18nProvider>");
  return context;
}

function readStoredLocale(): Locale {
  if (typeof window === "undefined") return DEFAULT_LOCALE;
  return normalizeLocale(localStorage.getItem(LOCALE_STORAGE_KEY));
}
